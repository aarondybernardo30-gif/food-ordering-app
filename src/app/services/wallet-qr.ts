import { Injectable } from '@angular/core';
import { BehaviorSubject, Observable } from 'rxjs';

export interface WalletQrSettings {
  /** The store's REAL wallet QR (image data URL or hosted image URL). Scannable in GCash/Maya. */
  image: string;
  /** Wallet app the QR belongs to, e.g. "GCash" or "Maya". */
  walletLabel: string;
  /** Registered name on the wallet account. */
  accountName: string;
  /** Wallet mobile number (also used to build a QR Ph code). */
  accountNumber: string;
  /** City registered with the account (required by the QR Ph standard). */
  city: string;
}

const STORAGE_KEY = 'app_wallet_qr';
const DEFAULTS: WalletQrSettings = {
  image: '',
  walletLabel: 'GCash',
  accountName: '',
  accountNumber: '',
  city: 'Manila'
};

/**
 * Store-level wallet payment settings. The admin uploads the store's REAL
 * wallet QR code (generated by their own GCash/Maya app) so customers can
 * scan it and send top-up payments.
 */
@Injectable({
  providedIn: 'root'
})
export class WalletQrService {
  private settingsSubject = new BehaviorSubject<WalletQrSettings>(this.read());
  public settings$: Observable<WalletQrSettings> = this.settingsSubject.asObservable();

  constructor() {
    window.addEventListener('storage', (e) => {
      if (e.key === STORAGE_KEY && e.newValue) {
        try {
          const parsed = JSON.parse(e.newValue);
          if (parsed && typeof parsed === 'object') {
            this.settingsSubject.next({ ...DEFAULTS, ...parsed });
          }
        } catch {}
      }
    });
  }

  private read(): WalletQrSettings {
    try {
      const data = localStorage.getItem(STORAGE_KEY);
      if (data) {
        const parsed = JSON.parse(data);
        if (parsed && typeof parsed === 'object') {
          return { ...DEFAULTS, ...parsed };
        }
      }
    } catch {}
    return { ...DEFAULTS };
  }

  getSettings(): WalletQrSettings {
    return this.settingsSubject.value;
  }

  update(settings: WalletQrSettings): void {
    const copy = { ...settings };
    this.settingsSubject.next(copy);
    localStorage.setItem(STORAGE_KEY, JSON.stringify(copy));
  }

  /** True once the admin has uploaded a real scannable QR. */
  hasRealQr(): boolean {
    return !!this.settingsSubject.value.image;
  }
}
